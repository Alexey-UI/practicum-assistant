import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import path from 'node:path';
import { readFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { serveProject } from './project-server.js';

const root = path.resolve(process.argv[2] ?? 'workspaces/mesto-ad');
const server = await serveProject(path.join(root, 'dist'));
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  // Isolate remote photos from an unstable network; application code remains real.
  const photo = await readFile(path.join(root, 'src/images/avatar.jpg'));
  await page.route('**/*', async route => {
    if (route.request().resourceType() === 'image' && new URL(route.request().url()).origin !== server.url) {
      await route.fulfill({ contentType: 'image/jpeg', body: photo });
    } else await route.continue();
  });
  await page.goto(server.url);
  const cards = page.locator('.card');
  await cards.nth(5).waitFor();
  assert.equal(await cards.count(), 6);
  assert.equal(await page.locator('form[novalidate]').count(), 3);
  const edit = page.locator('.popup_type_edit');
  const name = edit.locator('#user-name');
  const description = edit.locator('#user-description');
  const submitProfile = edit.locator('button[type="submit"]');
  const openProfile = page.locator('.profile__edit-button');
  await openProfile.click();
  assert.equal(await name.inputValue(), await page.locator('.profile__title').textContent());
  assert.equal(await description.inputValue(), await page.locator('.profile__description').textContent());
  assert.equal(await submitProfile.isDisabled(), true);
  await name.fill('Имя123');
  assert.match(await edit.locator('#user-name-error').innerText(), /Разрешены только/);
  assert.equal(await submitProfile.isDisabled(), true);
  await name.fill('');
  assert.ok(await edit.locator('#user-name-error').innerText());
  await name.fill('Я');
  assert.equal(await submitProfile.isDisabled(), true);
  await name.fill('Анна-Мария Ёлкина');
  await description.fill('Исследователь');
  assert.equal(await submitProfile.isEnabled(), true);
  await submitProfile.click();
  assert.equal(await page.locator('.profile__title').innerText(), 'Анна-Мария Ёлкина');
  await openProfile.click();
  await name.fill('Ошибка!');
  await page.keyboard.press('Escape');
  await openProfile.click();
  assert.equal(await name.inputValue(), 'Анна-Мария Ёлкина');
  assert.equal(await edit.locator('.popup__error_visible').count(), 0);
  assert.equal(await submitProfile.isDisabled(), true);
  await edit.locator('.popup__close').click();
  const newCard = page.locator('.popup_type_new-card');
  const cardName = newCard.locator('#place-name');
  const cardLink = newCard.locator('#place-link');
  const submitCard = newCard.locator('button[type="submit"]');
  const openCard = page.locator('.profile__add-button');
  await openCard.click();
  assert.equal(await cardName.inputValue(), '');
  assert.equal(await submitCard.isDisabled(), true);
  await cardName.fill('Новая карточка');
  await cardLink.fill('invalid');
  assert.ok(await newCard.locator('#place-link-error').innerText());
  assert.equal(await submitCard.isDisabled(), true);
  await cardLink.fill('https://example.test/photo.jpg');
  assert.equal(await submitCard.isEnabled(), true);
  await cardName.fill('Город1');
  assert.match(await newCard.locator('#place-name-error').innerText(), /Разрешены только/);
  await cardName.fill('Новая карточка');
  await submitCard.click();
  assert.equal(await cards.count(), 7);
  assert.equal(await cards.first().locator('.card__title').innerText(), 'Новая карточка');
  await openCard.click();
  assert.equal(await cardName.inputValue(), '');
  assert.equal(await cardLink.inputValue(), '');
  assert.equal(await newCard.locator('.popup__error_visible').count(), 0);
  assert.equal(await submitCard.isDisabled(), true);
  await page.keyboard.press('Escape');
  await cards.first().locator('.card__like-button').click();
  assert.equal(await cards.first().locator('.card__like-button_is-active').count(), 1);
  await cards.first().locator('.card__like-button').click();
  assert.equal(await cards.first().locator('.card__like-button_is-active').count(), 0);
  await cards.first().locator('.card__image').click();
  assert.equal(await page.locator('.popup_type_image.popup_is-opened').count(), 1);
  await page.locator('.popup__caption').waitFor({ state: 'visible' });
  assert.equal(await page.locator('.popup__caption').innerText(), 'Новая карточка');
  await page.locator('.popup_type_image').click({ position: { x: 3, y: 3 } });
  assert.equal(await page.locator('.popup_is-opened').count(), 0);
  await cards.first().locator('.card__control-button_type_delete').click();
  assert.equal(await cards.count(), 6);
  const avatar = page.locator('.popup_type_edit-avatar');
  const avatarLink = avatar.locator('#user-avatar');
  await page.locator('.profile__image').click();
  assert.equal(await avatarLink.inputValue(), '');
  await avatarLink.fill('not a url');
  assert.equal(await avatar.locator('button[type="submit"]').isDisabled(), true);
  await avatarLink.fill('https://example.test/avatar.jpg');
  await avatar.locator('button[type="submit"]').click();
  assert.match(await page.locator('.profile__image').getAttribute('style') ?? '', /example.test\/avatar.jpg/);
  await page.locator('.profile__image').click();
  assert.equal(await avatarLink.inputValue(), '');
  assert.equal(await avatar.locator('.popup__error_visible').count(), 0);
  assert.equal(await avatar.locator('button[type="submit"]').isDisabled(), true);
  await page.keyboard.press('Escape');
  await avatar.waitFor({ state: 'hidden' });
  const artifacts = fileURLToPath(new URL('../artifacts/mesto-local/', import.meta.url));
  await mkdir(artifacts, { recursive: true });
  for (const width of [320, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), width);
    await page.screenshot({ path: path.join(artifacts, `${width}.png`), fullPage: true });
  }
  assert.deepEqual(errors, []);
  console.log('Mesto: собранное приложение, 3 формы, HTML5-ограничения, ошибки и их очистка, состояние кнопок, профиль, аватар, карточки, лайки, удаление, модальные окна и 3 ширины проверены.');
} finally { await browser.close(); await server.close(); }
