import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import path from 'node:path';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { serveProject } from './project-server.js';

const server = await serveProject(path.resolve(process.argv[2] ?? 'workspaces/to-do'));
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const rows = page.locator('.to-do__item');
  const texts = page.locator('.to-do__item-text');
  const input = page.getByPlaceholder('Следующее дело...');
  const add = page.getByRole('button', { name: 'Добавить', exact: true });
  await page.goto(server.url);
  assert.equal(await rows.count(), 6);
  const defaults = await texts.allTextContents();
  let navigations = 0;
  page.on('framenavigated', frame => { if (frame === page.mainFrame()) navigations++; });
  await input.fill('  Купить молоко  ');
  await add.click();
  assert.equal(await rows.count(), 7);
  assert.equal(await texts.first().textContent(), 'Купить молоко');
  assert.equal(await input.inputValue(), '');
  assert.equal(navigations, 0, 'Adding must not navigate');
  await page.reload();
  assert.deepEqual(await texts.allTextContents(), ['Купить молоко', ...defaults]);
  await rows.nth(2).getByRole('button', { name: 'Копировать', exact: true }).click();
  assert.equal(await texts.first().textContent(), defaults[1]);
  assert.equal(await rows.count(), 8);
  await rows.first().getByRole('button', { name: 'Редактировать', exact: true }).click();
  assert.equal(await texts.first().getAttribute('contenteditable'), 'true');
  assert.equal(await texts.first().evaluate(el => el === document.activeElement), true);
  await texts.first().fill('Отредактированная копия');
  await input.click();
  assert.equal(await texts.first().getAttribute('contenteditable'), 'false');
  assert.equal(await texts.nth(3).textContent(), defaults[1], 'Editing a copy must not change the original');
  await page.reload();
  assert.equal(await texts.first().textContent(), 'Отредактированная копия');
  await rows.first().getByRole('button', { name: 'Редактировать', exact: true }).click();
  await texts.first().fill('Сохранено Enter');
  await page.keyboard.press('Enter');
  await page.reload();
  assert.equal(await texts.first().textContent(), 'Сохранено Enter');
  await rows.first().getByRole('button', { name: 'Редактировать', exact: true }).click();
  await texts.first().fill('Отмена');
  await page.keyboard.press('Escape');
  assert.equal(await texts.first().textContent(), 'Сохранено Enter');
  await rows.first().getByRole('button', { name: 'Редактировать', exact: true }).click();
  await texts.first().fill('  ');
  await input.click();
  assert.equal(await texts.first().textContent(), 'Сохранено Enter');
  await rows.first().getByRole('button', { name: 'Удалить', exact: true }).click();
  await page.reload();
  assert.deepEqual(await texts.allTextContents(), ['Купить молоко', ...defaults]);
  await input.fill('   ');
  await add.click();
  assert.equal(await rows.count(), 7);
  const literal = '<img src=x onerror="window.injected=true">';
  await input.fill(literal);
  await add.click();
  assert.equal(await texts.first().textContent(), literal);
  assert.equal(await rows.first().locator('img').count(), 0);
  await page.reload();
  assert.equal(await texts.first().textContent(), literal);
  assert.equal(await rows.first().locator('img').count(), 0);
  while (await rows.count()) await rows.first().getByRole('button', { name: 'Удалить', exact: true }).click();
  await page.reload();
  assert.equal(await rows.count(), 0, 'An empty saved list must stay empty');
  for (const corrupt of ['{invalid', '{"tasks":[]}', '[1,null]']) {
    await page.evaluate(value => localStorage.setItem('tasks', value), corrupt);
    await page.reload();
    assert.deepEqual(await texts.allTextContents(), defaults);
  }
  await page.evaluate(() => localStorage.removeItem('tasks'));
  await page.reload();
  assert.deepEqual(await texts.allTextContents(), defaults);
  await page.evaluate(() => {
    Storage.prototype.setItem = () => { throw new DOMException('Quota exceeded', 'QuotaExceededError'); };
  });
  await input.fill('Изменение при недоступном хранилище');
  await add.click();
  assert.equal(await rows.count(), 7);
  assert.match(await page.getByRole('status').innerText(), /Не удалось сохранить/);
  assert.deepEqual(errors, []);
  await page.reload();
  await page.evaluate(() => document.fonts.ready);
  const artifacts = fileURLToPath(new URL('../artifacts/todo-local/', import.meta.url));
  await mkdir(artifacts, { recursive: true });
  await page.screenshot({ path: path.join(artifacts, 'desktop.png'), fullPage: true });
  console.log('To-do: начальный список, добавление, копирование, удаление, редактирование, Enter/Escape, перезагрузка, пустой список, повреждённое/недоступное хранилище и текст без исполнения HTML проверены.');
} finally {
  await browser.close();
  await server.close();
}
